def partdv(TEMP, DNE, Z, NLEV, NE, GEE, ENRGY, S, U):
    """
    SUBROUTINE PARTDV(TEMP,DNE,Z,NLEV,NE,GEE,ENRGY,S,U)
    ===================================================

    对应 synspec54.f 行 16751-16779。
    标量哑元 U 被赋值 → 按约定返回全部标量哑元 (TEMP, DNE, Z, NLEV, U)。
    """
    # INCLUDE 'PARAMS.FOR'
    # DIMENSION GEE(*),ENRGY(*),S(*)
    # INTEGER NE(*)
    U = 0.0
    ET = TEMP / 11604.8
    P = (14.69e0 - 0.20 - 0.6667 * math.log10(DNE))
    for I in range(1, NLEV + 1):  # DO 10 I=1,NLEV
        U1 = float(NE[I])
        ZSTAR = Z - S[I]
        if ZSTAR > 0:
            W = P + 4. * math.log10(ZSTAR) - 4. * math.log10(U1)
        else:
            W = 0.0
        if W > 1.:
            W = 1.
        if (ENRGY[I] / ET) < 65.0:
            U1 = GEE[I] * W * math.exp(-ENRGY[I] / ET)
        else:
            U1 = 0.0
        U = U + U1
    # 10 CONTINUE
    return TEMP, DNE, Z, NLEV, U  # RETURN


