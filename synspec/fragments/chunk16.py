    part = partoh[it] + (partoh[it + 1] - partoh[it]) * (t - tn) * twhui

    # interpolate to obtain cross-section
    it = int((t - 2000.0) * fihui + 1.0)
    if it < 1:
        it = 1
    tn = float(it) * fihu + 1500.0
    # 同 SBFCH：`*PART` 所在续行是注释，part 未参与最终结果（按原文直译）
    sbfoh = math.exp((crossoht[it] + (crossoht[it + 1] - crossoht[it])
                      * (t - tn) * fihui) * tenl)
    return sbfoh


