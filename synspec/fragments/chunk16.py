def ougrid(abso):
    """subroutine ougrid(abso)

    output of grid opacities

    对应 synspec54.f 行 22093–22130
    """
    # INCLUDE 'PARAMS.FOR' / 'MODELP.FOR' / 'SYNTHP.FOR'
    # common/prfrgr/ipfreq,indext,indexn
    # common/gridf0/wlgrid(mfgrid),nfgrid
    # common/initab/absop(msftab),wltab(msftab),nfrtab(mttab,mrtab),inttab
    un = 1.0                  # parameter (un=1.,ten15=1.e-15,c18=2.997925e18)
    ten15 = 1.0e-15
    c18 = 2.997925e18
    # DIMENSION ABSO(MFREQ)

    d1 = un / C.DENS[1]
    if C.NFREQ <= 3:
        return

    if C.IPRIN < 4:
        for ij in range(3, C.NFREQ):        # do ij=3,nfreq-1
            abl = math.log(abso[ij] * d1)
            C.ipfreq += 1
            C.absop[C.ipfreq] = abl
            C.wltab[C.ipfreq] = 2.997925e18 / C.FREQ[ij]
    else:
        for ij in range(3, C.NFREQ):
            abl = math.log(abso[ij] * d1)
            C.ipfreq += 1
            # 637 format(i10,f14.5,0pf12.5)
            write_line(27, f"{C.ipfreq:10d}{c18 / C.FREQ[ij]:14.5f}{abl:12.5f}")
            C.absop[C.ipfreq] = abl
            C.wltab[C.ipfreq] = 2.997925e18 / C.FREQ[ij]

    return


