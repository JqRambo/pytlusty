def radtem():
    """SUBROUTINE RADTEM

    determination of the radiation temperatures
    after Schmutz (1991); inversion done by Newton-Raphson

    对应 synspec54.f 行 20744–20798
    """
    # INCLUDE 'PARAMS.FOR' / 'MODELP.FOR' / 'WINCOM.FOR'
    # common/velaux/velmax,iemoff,nltoff,itrad
    con = 2.0706e-16          # PARAMETER (CON=2.0706D-16, un=1.)
    un = 1.0
    nterad = 3                # parameter (nterad=3)

    for id in range(1, C.ND + 1):
        rx = C.RD[C.ND] / C.RD[id]
        # c WDIL(ID)=0.5*(1.-sqrt(1.-rx*rx))
        C.WDIL[id] = un - math.sqrt(un - rx * rx)
    for itrd in range(1, nterad + 1):
        if C.itrad == 0:
            for id in range(1, C.ND + 1):
                C.TRAD[itrd, id] = C.TEMP[id]
        else:
            ii = 0
            jj = 0
            if itrd <= C.NION:
                ii = C.NFIRST[itrd]
            if itrd <= C.NION:
                jj = C.NNEXT[itrd]
            for id in range(1, C.ND + 1):
                C.TRAD[itrd, id] = C.TEMP[id]
                if ii > 0:
                    # c IF(II.GT.100000) THEN
                    aa = C.POPUL[jj, id] / C.POPUL[ii, id] * C.ELEC[id] * con
                    aa = aa * C.G[ii] / C.G[jj] / C.WDIL[id] / math.sqrt(C.TEMP[id])
                    tr = C.TEMP[id]
                    iter = 0
                    # 标号 10：Newton-Raphson 迭代（GO TO 10 → while True）
                    while True:
                        iter += 1
                        xx = C.ENION[ii] / BOLK / tr
                        dtr = (aa * math.exp(xx) - tr) / (1.0 + xx)
                        dtrr = dtr / tr
                        tr = tr + dtr
                        if not (abs(dtrr) > 1.0e-3 and iter < 100):
                            break  # IF(... ) GO TO 10 条件不成立，退出迭代
                    C.TRAD[itrd, id] = tr
    # 600 format(/' radiation temperatures/')
    print()
    print(' radiation temperatures/')
    for id in range(1, C.ND + 1):
        # 601 format(i5,4f10.1)
        print(f"{id:5d}{C.TEMP[id]:10.1f}{C.TRAD[1, id]:10.1f}"
              f"{C.TRAD[2, id]:10.1f}{C.TRAD[3, id]:10.1f}")
    return


