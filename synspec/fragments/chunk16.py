def intxen(w0b, w0r, x0, z0, iwl, iline):
    """SUBROUTINE INTXEN(W0B,W0R,X0,Z0,IWL,ILINE)

    Interpolation in temperature and electron density from the
    Xenomorph tables for hydrogen lines to the actual valus of
    temperature and electron density

    修改标量哑元 W0B、W0R → 返回全部标量哑元 (w0b, w0r, x0, z0, iwl, iline)。
    对应 synspec54.f 行 21547–21595
    """
    # INCLUDE 'PARAMS.FOR' / 'MODELP.FOR'
    zz = np.zeros(4)    # DIMENSION ZZ(3),XX(3),WXB(3),WZB(3),WXR(3),WZR(3)
    xx = np.zeros(4)
    wxb = np.zeros(4)
    wzb = np.zeros(4)
    wxr = np.zeros(4)
    wzr = np.zeros(4)

    nx = 2
    nz = 2
    nt = C.NTHXEN[iline]
    ne = C.NEHXEN[iline]

    ipz = 0  # 若 NE-1<1 则 DO 10 不执行，Fortran 中 IPZ 未定义；此处先置 0
    for izz in range(1, ne):        # DO 10 IZZ=1,NE-1
        ipz = izz
        if z0 <= C.XNEXEN[izz + 1, iline]:
            break                   # GO TO 20
    # 标号 20
    n0z = ipz - idiv(nz, 2) + 1     # Fortran 整数除法 NZ/2
    if n0z < 1:
        n0z = 1
    if n0z > ne - nz + 1:
        n0z = ne - nz + 1
    n1z = n0z + nz - 1

    for izz in range(n0z, n1z + 1):
        i0z = izz - n0z + 1
        zz[i0z] = C.XNEXEN[izz, iline]
        ipx = 0  # 同上，循环不执行时 Fortran 中 IPX 未定义
        for ix in range(1, nt):     # DO 30 IX=1,NT-1
            ipx = ix
            if x0 <= C.XTXEN[ix + 1, iline]:
                break               # GO TO 40
        # 标号 40
        n0x = ipx - idiv(nx, 2) + 1
        if n0x < 1:
            n0x = 1
        if n0x > nt - nx + 1:
            n0x = nt - nx + 1
        n1x = n0x + nx - 1
        for ix in range(n0x, n1x + 1):
            i0 = ix - n0x + 1
            xx[i0] = C.XTXEN[ix, iline]
            wxb[i0] = C.PRFXB[iline, iwl, ix, izz]
            wxr[i0] = C.PRFXR[iline, iwl, ix, izz]
        wzb[i0z] = yint(xx, wxb, x0)
        wzr[i0z] = yint(xx, wxr, x0)
    w0b = yint(zz, wzb, z0)
    w0r = yint(zz, wzr, z0)
    return w0b, w0r, x0, z0, iwl, iline


def gomini():
    """SUBROUTINE GOMINI

    Initialization and reading of the opacity table for thermal processe
    and Rayleigh scattering
    raytab: scattering opacities in cm^2/gm at 5.0872638d14 Hz (sodium D)
    (NOTE: Quantities in rayleigh.tab are in log_e)

    tempvec: array of temperatures
    rhovec: array of densities (gm/cm^3)
    nu:     array of frequencies
    table:  absorptive opacities in cm^2/gm
    (NOTE:  Quantities in absorption.tab are in log_e)

    对应 synspec54.f 行 21601–21695
    """
    # INCLUDE 'PARAMS.FOR' / 'MODELP.FOR'
    # COMMON/GOMOPA/frgtab(mfhtab),wlgtab(mfhtab),hydopg(mfhtab,mdepth),nugfreq
    # common/gompar/hglim,ihgom
    temvec = np.zeros(MTABTH + 1)   # dimension temvec(mtabth)
    elevec = np.zeros(MTABEH + 1)   #           elevec(mtabeh)
    hydcrs = np.zeros((MTABTH + 1, MTABEH + 1, MFHTAB + 1))  # hydcrs(mtabth,mtabeh,mfhtab)

    if C.ihgom == 0:
        return

    open_unit(53, 'gomhyd.dat', 'r')    # open(53,file='gomhyd.dat',status='old')

    # read(53,*) nugfreq,nugtemp,nugele
    _t = read_line(53).split()
    C.nugfreq = int(_t[0])
    nugtemp = int(_t[1])
    nugele = int(_t[2])
    read_line(53)                       # read(53,*) —— 跳过一行
    # read(53,*) (temvec(i),i=1,nugtemp)
    _v = []
    while len(_v) < nugtemp:
        _v += read_line(53).split()
    for i in range(1, nugtemp + 1):
        temvec[i] = float(_v[i - 1])
    read_line(53)                       # read(53,*)
    # read(53,*) (elevec(j),j=1,nugele)
    _v = []
    while len(_v) < nugele:
        _v += read_line(53).split()
    for j in range(1, nugele + 1):
        elevec[j] = float(_v[j - 1])
    for it in range(1, nugtemp + 1):
        temvec[it] = math.log(temvec[it] * 1.161e4)
    # c     write(6,600) ihgom,nugfreq,nugtemp,nugele
    # c 600 format(' ihgom,nugfr,nugt,nuge ',4i4)

    egtab1 = elevec[1]
    egtab2 = elevec[nugele]
    tgtab1 = temvec[1]
    tgtab2 = temvec[nugtemp]

    for k in range(1, C.nugfreq + 1):
        # read(53,501) eneev；501 format(40x,f17.14)
        eneev = float(read_line(53)[40:57])
        C.frgtab[k] = 3.28805e15 / 13.595 * eneev
        C.wlgtab[k] = 2.997925e18 / C.frgtab[k]
        for i in range(1, nugtemp + 1):
            # read(53,*) (hydcrs(i,j,k),j=1,nugele)
            _v = []
            while len(_v) < nugele:
                _v += read_line(53).split()
            for j in range(1, nugele + 1):
                hydcrs[i, j, k] = float(_v[j - 1])
    frg1 = C.frgtab[1]
    frg2 = C.frgtab[C.nugfreq]

    close_unit(53)

    #     Interpolate to the actual temperature and electron density
    #     at the individual depth points
    for id in range(1, C.ND + 1):       # do 10 id=1,nd
        if C.ELEC[id] < C.hglim:
            continue                    # go to 10
        rl = math.log(C.ELEC[id])
        tl = math.log(C.TEMP[id])

        deltar = (rl - egtab1) / (egtab2 - egtab1) * float(nugele - 1)
        jr = 1 + int(dint(deltar))      # IDINT 截断取整
        if jr < 1:
            jr = 1
        if jr > nugele - 1:
            jr = nugele - 1
        r1i = elevec[jr]
        r2i = elevec[jr + 1]
        dri = (rl - r1i) / (r2i - r1i)
        if jr == 1:
            dri = 0.0

        deltat = (tl - tgtab1) / (tgtab2 - tgtab1) * float(nugtemp - 1)
        jp = 1 + int(dint(deltat))
        if jp < 1:
            jp = 1
        if jp > nugtemp - 1:
            jp = nugtemp - 1
        t1i = temvec[jp]
        t2i = temvec[jp + 1]
        dti = (tl - t1i) / (t2i - t1i)
        if jp == 1:
            dti = 0.0

        # loop over tabular frequencies
        for jf in range(1, C.nugfreq + 1):
            opr1 = (hydcrs[jp, jr, jf] + dti
                    * (hydcrs[jp + 1, jr, jf] - hydcrs[jp, jr, jf]))
            opr2 = (hydcrs[jp, jr + 1, jf] + dti
                    * (hydcrs[jp + 1, jr + 1, jf] - hydcrs[jp, jr + 1, jf]))
            opac = opr1 + dri * (opr2 - opr1)
            C.hydopg[jf, id] = opac + math.log(0.02654 * 4.1347e-15)
    # 10 continue
    return


def ghydop(id, i0, i1, pj, absoh, emish):
    """subroutine ghydop(id,i0,i1,pj,absoh,emish)

    hydrogen opacity -- lines + pseudocontinuum from Gomez tables

    数组哑元 absoh、emish 就地修改；标量哑元不修改，无返回。
    对应 synspec54.f 行 21700–21749
    """
    # INCLUDE 'PARAMS.FOR' / 'MODELP.FOR' / 'SYNTHP.FOR'
    # COMMON/GOMOPA/frgtab(mfhtab),wlgtab(mfhtab),hydopg(mfhtab,mdepth),nugfreq
    # dimension absoh(mfreq),emish(mfreq),pj(40)

    frg1 = C.frgtab[1]
    frg2 = C.frgtab[C.nugfreq]
    igf = 0
    for ij in range(i0, i1 + 1):        # do 20 ij=i0,i1
        fr = C.FREQ[ij]
        if fr < frg1 or fr > frg2:
            continue                    # go to 20
        wla = 2.997925e18 / fr
        frl = math.log10(fr)

        if ij == i0:
            igf = C.nugfreq
        # 标号 10：if(wla.gt.wlgtab(igf)) igf=igf-1; go to 10
        while wla > C.wlgtab[igf]:
            igf -= 1
        ig0 = igf
        if ig0 <= 2:
            ig0 = 2
        ig1 = igf - 1
        abl = ((C.hydopg[ig1, id] - C.hydopg[ig0, id]) * (wla - C.wlgtab[ig0])
               / (C.wlgtab[ig1] - C.wlgtab[ig0]) + C.hydopg[ig0, id])

        ii = 1
        if C.FREQ[ij] > 8.22013e14:
            pp = pj[1] * 2.0
        else:
            pp = pj[2] * 8.0

        f15 = fr * 1.0e-15
        xkf = math.exp(-4.79928e-11 * fr / C.TEMP[id])
        xkfb = xkf * 1.4743e-2 * f15 * f15 * f15

        oph = math.exp(abl) * pp
        absoh[ij] = absoh[ij] + oph
        emish[ij] = emish[ij] + oph * xkfb / (1.0 - xkf)
    # 20 continue
    return


def ingrid(mode, inext, igrd):
    """subroutine ingrid(mode,inext,igrd)

    setting state parameters for the opacity grid calculations

    input:
          temp1 - lowest value of T
          temp2 - largest value of T
          ntemp - number of temperature values
          dens1 - lowest value of the density parameter
          dens2 - largest value of the density parameter
          ndens - number of the density parameter values

          isdens = 0 - density parameter is electron density
                 > 0 - density parameter is mass density
                 < 0 - density parameter is gas pressure

    修改标量哑元 INEXT → 返回全部标量哑元 (mode, inext, igrd)。
    对应 synspec54.f 行 21754–22087
    """
    # INCLUDE 'PARAMS.FOR' / 'MODELP.FOR' / 'LINDAT.FOR'
    un = 1.0                  # parameter (un=1.,ten15=1.e-15,c18=2.997925e18)
    ten15 = 1.0e-15
    c18 = 2.997925e18
    # real*4 absgrd(mttab,mrtab,mfgrid) —— 属 common/fintab/，即 C.absgrd
    # common/alsave/ALAM0s,ALASTs,CUTOF0s,CUTOFSs,RELOPs,SPACEs
    # common/gridp0/tempg,densg,elecgr,densg0,temp1,ntemp,ndens,nden
    # common/gridf0/wlgrid,nfgrid
    # common/prfrgr/ipfreq,indext,indexn
    # common/igrddd/igrdd,irelin
    # common/initab/absop,wltab,nfrtab,inttab
    # common/elecm0/elecm(mdepth)
    # common/timeta/dtim
    # common/relabu/relabn(matom),popul0(mlevel,1)
    abgrd = np.zeros(MFGRID + 1)   # dimension abgrd(mfgrid)
    xli = np.zeros(4)              # dimension xli(3)
    # character*(80) tabname；common/tabout/tabname,ibingr,idens
    templ = np.zeros(MTTAB + 1)    # dimension templ(mttab)

    # --------------
    # initialization
    # --------------
    C.igrdd = igrd
    if mode == 0:
        # read(2,*) ntemp,temp1,temp2
        _t = read_line(2).split()
        C.ntemp = int(_t[0])
        C.temp1 = float(_t[1])
        temp2 = float(_t[2])
        C.idens = int(read_line(2).split()[0])   # read(2,*) idens
        if C.idens < 10:
            # read(2,*) ndens,dens1,dens2
            _t = read_line(2).split()
            C.ndens = int(_t[0])
            dens1 = float(_t[1])
            dens2 = float(_t[2])
        elif C.idens < 20:
            # read(2,*) ndens,densl1,densl2,densu1,densu2
            _t = read_line(2).split()
            C.ndens = int(_t[0])
            densl1 = float(_t[1])
            densl2 = float(_t[2])
            densu1 = float(_t[3])
            densu2 = float(_t[4])
        else:
            for it in range(1, C.ntemp + 1):
                # read(2,*) ndens,densl,densu
                _t = read_line(2).split()
                C.ndens = int(_t[0])
                densl = float(_t[1])
                densu = float(_t[2])
                C.densg[it, 1] = densl
                C.densg[it, C.ndens] = densu
                C.nden[it] = C.ndens
        if C.idens < 20:
            for it in range(1, C.ntemp + 1):
                C.nden[it] = C.ndens
        if C.IFEOS <= 0:
            # read(2,*) nfgrid,inttab,wlam1,wlam2
            _t = read_line(2).split()
            C.nfgrid = int(_t[0])
            C.inttab = int(_t[1])
            wlam1 = float(_t[2])
            wlam2 = float(_t[3])
            # read(2,*) tabname,ibingr
            _t = read_line(2).split()
            C.tabname = _t[0]
            C.ibingr = int(_t[1])

        irsct = 0
        irsche = 0
        irsch2 = 0

        wl1 = math.log(wlam1)
        wl2 = math.log(wlam2)
        dwl = (wl2 - wl1) / (C.nfgrid - 1)
        for i in range(1, C.nfgrid + 1):
            C.wlgrid[i] = math.exp(wl1 + (i - 1) * dwl)

        if C.temp1 > 0.0:
            at1 = math.log(C.temp1)
            at2 = math.log(temp2)
            dt = 0.0
            if C.ntemp > 1:
                dt = (at2 - at1) / (C.ntemp - 1)
            for i in range(1, C.ntemp + 1):
                templ[i] = at1 + (i - 1) * dt
                C.tempg[i] = math.exp(templ[i])
            if C.idens < 10:
                at1 = math.log(dens1)
                at2 = math.log(dens2)
                dr = 0.0
                C.ndens = C.nden[1]
                if C.ndens > 0:
                    dr = (at2 - at1) / (C.ndens - 1)
                for i in range(1, C.ntemp + 1):
                    for j in range(1, C.ndens + 1):
                        C.densg[i, j] = math.exp(at1 + (j - 1) * dr)
            elif C.idens < 20:
                rhol1 = math.log(densl1)
                rhol2 = math.log(densl2)
                rhou1 = math.log(densu1)
                rhou2 = math.log(densu2)
                for i in range(1, C.ntemp + 1):
                    C.ndens = C.nden[i]
                    dens1 = rhol1 + (rhou1 - rhol1) / (at2 - at1) * (templ[i] - at1)
                    dens2 = rhol2 + (rhou2 - rhol2) / (at2 - at1) * (templ[i] - at1)
                    dr = 0.0
                    if C.ndens > 1:
                        dr = (dens2 - dens1) / (C.ndens - 1)
                    for j in range(1, C.ndens + 1):
                        C.densg[i, j] = math.exp(dens1 + (j - 1) * dr)
            else:
                for i in range(1, C.ntemp + 1):
                    C.ndens = C.nden[i]
                    at1 = math.log(C.densg[i, 1])
                    at2 = math.log(C.densg[i, C.ndens])
                    dr = 0.0
                    if C.ndens > 0:
                        dr = (at2 - at1) / (C.ndens - 1)
                    for j in range(2, C.ndens):     # do j=2,ndens-1
                        C.densg[i, j] = math.exp(at1 + (j - 1) * dr)

            # 621 format(/' COMPUTING AN OPACITY TABLE WITH GRID PARAMETERS:'/
            #  *   ' ===== ntemp, ndens ',2i4)
