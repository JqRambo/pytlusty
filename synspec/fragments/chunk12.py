def matinv(a, n, nr):
    """
C     =========================
C
C     Matrix inversion
C      by LU decomposition
C
C      A  -  matrix of actual size (N x N) and maximum size (NR x NR)
C            to be inverted;
C      Inversion is accomplished in place and the original matrix is
C      replaced by its inverse
C
    对应 synspec54.f 行 14736–14811
    """
    # IF(N.EQ.1) GO TO 250
    if n == 1:
        # 标号 250
        a[1, 1] = 1.0 / a[1, 1]
        return
    for i in range(2, n + 1):                # DO 50 I=2,N
        im1 = i - 1
        for j in range(1, im1 + 1):          # DO 20 J=1,IM1
            jm1 = j - 1
            div = a[j, j]
            sum = 0.0
            # IF(JM1.LT.1) GO TO 20 → 跳过求和，直接执行标号 20 的赋值
            if jm1 >= 1:
                for k in range(1, jm1 + 1):  # DO 10 K=1,JM1
                    sum = sum + a[i, k] * a[k, j]
            # 标号 20
            a[i, j] = (a[i, j] - sum) / div
        for j in range(i, n + 1):            # DO 40 J=I,N
            sum = 0.0
            for k in range(1, im1 + 1):      # DO 30 K=1,IM1
                sum = sum + a[i, k] * a[k, j]
            # 标号 40
            a[i, j] = a[i, j] - sum
    for ii in range(2, n + 1):               # DO 80 II=2,N
        i = n + 2 - ii
        im1 = i - 1
        if im1 < 1:
            continue                         # GO TO 80
        for jj in range(1, im1 + 1):         # DO 70 JJ=1,IM1
            j = i - jj
            jp1 = j + 1
            sum = 0.0
            # IF(JP1.GT.IM1) GO TO 70 → 跳过求和，直接执行标号 70 的赋值
            if jp1 <= im1:
                for k in range(jp1, im1 + 1):  # DO 60 K=JP1,IM1
                    sum = sum + a[i, k] * a[k, j]
            # 标号 70
            a[i, j] = -a[i, j] - sum
    for ii in range(1, n + 1):               # DO 110 II=1,N
        i = n + 1 - ii
        div = a[i, i]
        ip1 = i + 1
        # IF(IP1.GT.N) GO TO 110 → 跳过内层循环，但仍执行标号 110 的赋值
        if ip1 <= n:
            for jj in range(ip1, n + 1):     # DO 100 JJ=IP1,N
                j = n + ip1 - jj
                sum = 0.0
                for k in range(ip1, j + 1):  # DO 90 K=IP1,J
                    sum = sum + a[i, k] * a[k, j]
                a[i, j] = -sum / div
        # 标号 110
        a[i, i] = 1.0 / a[i, i]

    for i in range(1, n + 1):                # DO 240 I=1,N
        for j in range(1, n + 1):            # DO 230 J=1,N
            k0 = i
            # IF(J.GE.I) GO TO 220
            if j >= i:
                # 标号 220
                k0 = j
                sum = a[i, k0]
                if k0 != n:                  # IF(K0.EQ.N) GO TO 230
                    k0 = k0 + 1
                    # GO TO 200
                    for k in range(k0, n + 1):  # DO 210 K=K0,N
                        sum = sum + a[i, k] * a[k, j]
            else:
                sum = 0.0
                # 标号 200
                for k in range(k0, n + 1):   # DO 210 K=K0,N
                    sum = sum + a[i, k] * a[k, j]
            # 标号 230（GO TO 230 也落到这里）
            a[i, j] = sum
    return


def lineqs(a, b, x, n, nr):
    """
C     =============================
C
C     Solution of the linear system A*X=B
C     by Gaussian elimination with partial pivoting
C
C     Input: A  - matrix of the linear system, with actual size (N x N),
C                and maximum size (NR x NR)
C            B  - the rhs vector
C     Output: X - solution vector
C     Note that matrix A and vector B are destroyed here !
C
    对应 synspec54.f 行 14818–14880
    """
    d = np.zeros(MLEVEL + 1)                 # DIMENSION D(MLEVEL)
    ip = np.zeros(MLEVEL + 1, dtype=np.int64)  # DIMENSION IP(MLEVEL)
    for i in range(1, n + 1):                # DO 70 I=1,N
        for j in range(1, n + 1):            # DO 10 J=1,N
            d[j] = a[j, i]
        im1 = i - 1
        # IF(IM1.LT.1) GO TO 40
        if im1 >= 1:
            for j in range(1, im1 + 1):      # DO 30 J=1,IM1
                it = ip[j]
                a[j, i] = d[it]
                d[it] = d[j]
                jp1 = j + 1
                for k in range(jp1, n + 1):  # DO 20 K=JP1,N
                    d[k] = d[k] - a[k, j] * a[j, i]
        # 标号 40
        am = abs(d[i])
        ip[i] = i
        for k in range(i, n + 1):            # DO 50 K=I,N
            if am >= abs(d[k]):
                continue                     # GO TO 50
            ip[i] = k
            am = abs(d[k])
        it = ip[i]
        a[i, i] = d[it]
        d[it] = d[i]
        ip1 = i + 1
        if ip1 > n:
            break                            # GO TO 80 → 跳出循环 70
        for k in range(ip1, n + 1):          # DO 60 K=IP1,N
            a[k, i] = d[k] / a[i, i]
    # 标号 80
    for i in range(1, n + 1):                # DO 100 I=1,N
        it = ip[i]
        x[i] = b[it]
        b[it] = b[i]
        ip1 = i + 1
        if ip1 > n:
            break                            # GO TO 110 → 跳出循环 100
        for j in range(ip1, n + 1):          # DO 90 J=IP1,N
            b[j] = b[j] - a[j, i] * x[i]
    # 标号 110
    for i in range(1, n + 1):                # DO 140 I=1,N
        k = n - i + 1
        sum = 0.0
        kp1 = k + 1
        # IF(KP1.GT.N) GO TO 130
        if kp1 <= n:
            for j in range(kp1, n + 1):      # DO 120 J=KP1,N
                sum = sum + a[k, j] * x[j]
        # 标号 130
        x[k] = (x[k] - sum) / a[k, k]
    return


def expint(x):
    """
C     ==================
C
C     First exponential integral function E1(X)
C
    对应 synspec54.f 行 14887–14904
    """
    if x <= 1.0:
        expint_v = (-math.log(x) - 0.57721566 + x * (0.99999193 + x * (-0.24991055
                    + x * (0.05519968 + x * (-0.00976004 + x * 0.00107857)))))
    else:
        expint_v = (math.exp(-x) * ((0.2677734343 + x * (8.6347608925 + x *
                    (18.059016973 + x * (8.5733287401 + x)))) /
                    (3.9584969228 + x * (21.0996530827 + x *
                    (25.6329561486 + x * (9.5733223454 + x))))) / x)
    return expint_v


def interp(x, y, xx, yy, nx, nxx, npol, ilogx, ilogy):
    """
C     ====================================================
C
C     General interpolation procedure of the (NPOL-1)-th order
C
C     for  ILOGX = 1  logarithmic interpolation in X
C     for  ILOGY = 1  logarithmic interpolation in Y
C
C     Input:
C      X    - array of original x-coordinates
C      Y    - array of corresponding functional values Y=y(X)
C      NX   - number of elements in arrays X or Y
C      XX   - array of new x-coordinates (to which is to be
C             interpolated
C      NXX  - number of elements in array XX
C     Output:
C      YY   - interpolated functional values YY=y(XX)
C
    对应 synspec54.f 行 14911–14992
    """
    # 语句函数 EXP10(X0)=EXP(X0*2.30258509299405D0)
    def exp10(x0):
        return math.exp(x0 * 2.30258509299405)

    # IF(NPOL.LE.0.OR.NX.LE.0) GO TO 200
    if npol <= 0 or nx <= 0:
        # 标号 200
        n = nx
        if nxx >= nx:
            n = nxx
        for i in range(1, n + 1):
            xx[i] = x[i]
            yy[i] = y[i]
        return
    if ilogx != 0:
        for i in range(1, nx + 1):
            x[i] = math.log10(x[i])
        for i in range(1, nxx + 1):
            xx[i] = math.log10(xx[i])
    if ilogy != 0:
        for i in range(1, nx + 1):
            y[i] = math.log10(y[i])
    nm = idiv(npol + 1, 2)                   # Fortran 整数除法 (NPOL+1)/2
    nm1 = nm + 1
    nup = nx + nm1 - npol
    for id in range(1, nxx + 1):             # DO ID=1,NXX
        xxx = xx[id]
        for i in range(nm1, nup + 1):        # DO I=NM1,NUP
            if xxx <= x[i]:
                break                        # GO TO 70
        else:
            i = nup                          # 循环正常结束后执行 I=NUP
        # 标号 70
        j = i - nm
        jj = j + npol - 1
        yyy = 0.0
        for k in range(j, jj + 1):           # DO K=J,JJ
            t = 1.0
            for m in range(j, jj + 1):       # DO 80 M=J,JJ
                if k == m:
                    continue                 # GO TO 80
                t = t * (xxx - x[m]) / (x[k] - x[m])
            yyy = y[k] * t + yyy
        yy[id] = yyy
    if ilogx != 0:
        for i in range(1, nx + 1):
            x[i] = exp10(x[i])
        for i in range(1, nxx + 1):
            xx[i] = exp10(xx[i])
    if ilogy != 0:
        for i in range(1, nx + 1):
            y[i] = exp10(y[i])
        for i in range(1, nxx + 1):
            yy[i] = exp10(yy[i])
    return


def intrp(wltab, absop, wlgrid, abgrd, nfr, nfgrid):
    """
c     =====================================================
c
c     a more efficient interpolation routine - using bisection
c
    对应 synspec54.f 行 14997–15040
    """
    yint = np.zeros(MFGRID + 1)              # dimension yint(mfgrid)
    jint = np.zeros(MFGRID + 1, dtype=np.int64)  # dimension jint(mfgrid)

    # set up interpolation coefficients for an interpolation
    # by bisection
    fr1 = wltab[1]
    fr2 = wltab[nfr]
    for ij in range(1, nfgrid + 1):
        xint = wlgrid[ij]
        jl = 0
        ju = nfr + 1
        # 标号 10（GO TO 10 → while 循环）
        while ju - jl > 1:
            jm = idiv(ju + jl, 2)            # Fortran 整数除法 (JU+JL)/2
            # IF((FR2.GT.FR1).EQV.(XINT.GT.WLTAB(JM)))
            if (fr2 > fr1) == (xint > wltab[jm]):
                jl = jm
            else:
                ju = jm
        j = jl
        if j == nfr:
            j = j - 1
        if j == 0:
            j = j + 1
        jint[ij] = j
        # c           yint(ij)=un/log10(wltab(j+1)/wltab(j))（原代码注释掉的形式）
        yint[ij] = 1.0 / (wltab[j + 1] - wltab[j])

    for ij in range(1, nfgrid + 1):
        j = jint[ij]
        rc = (absop[j + 1] - absop[j]) * yint[ij]
        # c           abgrd(ij)=rc*log10(wlgrid(ij)/wltab(j))+absop(j)（原代码注释掉的形式）
        abgrd[ij] = rc * (wlgrid[ij] - wltab[j]) + absop[j]
    return
